#!/usr/bin/env python3
"""Multi-store picker for the Click613 grocery price sites (Paltiel, Oct 18 2026).
Injects the MS_V1 block (multistore.js beside this file) into <site>/app.js just before the final "})();".
Idempotent: a site that already has MS_V1 gets the block replaced with the current version.
  python3 multistore.py <site_dir> [<site_dir> ...]
app.js is not regenerated by any build/refresh (they patch it in place), so this survives refreshes; refresh scripts
may still call it (cheap, no-op when current)."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
BLOCK = open(os.path.join(HERE, "multistore.js")).read().strip("\n")
def patch(src):
    if "/*MS_V1 " in src:
        new = re.sub(r"\n/\*MS_V1 multi-store picker.*?/\*MS_V1 end\*/", lambda m: "\n" + BLOCK, src, flags=re.S)
        return new, ("updated" if new != src else "current")
    i = src.rstrip().rfind("})();")
    if i < 0: raise SystemExit("no closing })(); in app.js")
    return src[:i] + BLOCK + "\n" + src[i:], "added"
if __name__ == "__main__":
    for site in sys.argv[1:]:
        f = os.path.join(site, "app.js"); s = open(f).read(); n, st = patch(s)
        if n != s: open(f, "w").write(n)
        print("multistore", site, st)
