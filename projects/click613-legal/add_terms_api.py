#!/usr/bin/env python3
"""Click613 grocery API (click613grocery-api): adds the Terms & Disclaimer to src/ (idempotent; re-run after editing disclaimer.html).
- src/_worker.js: a "terms" object on every /api/v1/* JSON answer, a Link rel=terms-of-service header on static JSON, and /terms (+ /disclaimer.html) served as the page.
- src/index.html: one footer line linking to /terms.
build_api.py copies src/ into site/ on every build, so the 5:40 AM rebuild keeps it."""
# --- repo paths (added for the GitHub version): projects/ folder = C613_WORK, defaults to this repo's projects/ ---
import os as _c613_os, sys as _c613_sys
_W = _c613_os.environ.get("C613_WORK") or _c613_os.path.abspath(_c613_os.path.join(_c613_os.path.dirname(_c613_os.path.abspath(__file__)), ".."))
# ---
import os, re, json
HERE = os.path.dirname(os.path.abspath(__file__)); SRC = f"{_W}/grocery-bot-api/src"
page = open(os.path.join(HERE, "disclaimer.html")).read().replace('href="./"', 'href="/"')
NOTICE = ("Information only, provided as is, without warranties. Prices are collected from public sources (some estimated) and may be wrong or out of date; "
          "the store's shelf/register price governs. Click613 does not certify kashrus; check the hechsher and ask your Rav. Eruv data is approximate and not a halachic ruling; "
          "check the local eruv before Shabbos. Click613 is not responsible for errors.")
BLOCK = (f"// >>> c613 terms (generated by projects/click613-legal/add_terms_api.py; do not edit by hand)\n"
         "const TERMS = " + json.dumps({"notice": NOTICE, "url": "https://click613grocery-api.sites.tab.bot/terms"}, ensure_ascii=False) + ";\n"
         "const TERMS_HTML = " + json.dumps(page, ensure_ascii=False) + ";\n"
         "// <<< c613 terms\n")
W = os.path.join(SRC, "_worker.js"); w = open(W).read(); w0 = w
w = re.sub(r"// >>> c613 terms.*?// <<< c613 terms\n", "", w, flags=re.S)
anchor = 'const H = { "content-type": "application/json; charset=utf-8", "access-control-allow-origin": "*" };\n'
assert anchor in w, "H anchor"
w = w.replace(anchor, anchor + BLOCK, 1)
oldJ = 'const J = (o, s = 200, cache = "no-store") => new Response(JSON.stringify(o, null, 1), { status: s, headers: { ...H, "cache-control": cache } });'
newJ = 'const J = (o, s = 200, cache = "no-store") => new Response(JSON.stringify(o && typeof o === "object" && !Array.isArray(o) && !o.terms ? { ...o, terms: TERMS } : o, null, 1), { status: s, headers: { ...H, "cache-control": cache, link: "<" + TERMS.url + ">; rel=\\"terms-of-service\\"" } });'
if oldJ in w: w = w.replace(oldJ, newJ, 1)
assert newJ in w, "J"
r1 = '    if (!P.startsWith("/api/v1/")) {\n'
r1n = r1 + '      if (P === "/terms" || P === "/terms/" || P === "/disclaimer.html" || P === "/disclaimer") return new Response(TERMS_HTML, { headers: { "content-type": "text/html; charset=utf-8", "cache-control": "public, max-age=900" } });\n'
if r1n not in w:
    assert r1 in w, "route anchor"; w = w.replace(r1, r1n, 1)
s1 = 'h.set("cache-control", "public, max-age=900"); if (P.endsWith(".geojson"))'
s1n = 'h.set("cache-control", "public, max-age=900"); h.set("link", "<" + TERMS.url + ">; rel=\\"terms-of-service\\""); if (P.endsWith(".geojson"))'
if s1n not in w:
    assert s1 in w, "static anchor"; w = w.replace(s1, s1n, 1)
p1 = 'return new Response(r.body, { status: 200, headers: { ...H, "content-type": type, "cache-control": "public, max-age=900" } }); };'
p1n = 'return new Response(r.body, { status: 200, headers: { ...H, "content-type": type, "cache-control": "public, max-age=900", link: "<" + TERMS.url + ">; rel=\\"terms-of-service\\"" } }); };'
if p1n not in w:
    assert p1 in w, "pass anchor"; w = w.replace(p1, p1n, 1)
if w != w0: open(W, "w").write(w)
I = os.path.join(SRC, "index.html"); h = open(I).read(); h0 = h
h = re.sub(r'<p class="c613legal".*?</p>', '', h, flags=re.S)
line = ('<p class="c613legal" style="color:#667;font-size:.85em;line-height:1.5">Data is for information only, provided as is and may be wrong or out of date; '
        'prices are collected from public sources (some estimated), the store\'s price governs, kashrus and eruv status must be confirmed locally. '
        'Click613 is not responsible for errors. Every API answer carries a <code>terms</code> field; please show a short "confirm in store" note with prices. '
        '<a href="/terms">Terms &amp; disclaimer</a></p>')
h = h.replace('</main></body></html>', line + '</main></body></html>', 1)
assert line in h, "index anchor"
if h != h0: open(I, "w").write(h)
print("api terms ok")
